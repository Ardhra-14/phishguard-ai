"""
Phase 3.1 — Training dataset builder.

Pulls labeled URLs from public sources and runs each one through the same
FeaturePipeline used in production (backend/features/pipeline.py), so the
training data is generated by the exact same code path that will score
live traffic later. Writes a flat CSV: url, domain, label, <41 feature
keys>.

Sources
-------
Phishing (label=1): the OpenPhish Community Feed, via its GitHub mirror
    (github.com/openphish/public_feed). The mirror commits a fresh
    ~300-URL snapshot roughly twice a day; the live feed.txt endpoint only
    ever holds the *current* snapshot (~300-500 URLs), so we walk back
    through git history and de-duplicate across snapshots to accumulate
    enough volume. Verified: ~7 days of history -> ~2000 unique URLs.

Legit (label=0): the Tranco top sites list (tranco-list.eu/top-1m.csv.zip).
    No API key needed for the default list. We deliberately do NOT just
    take the literal top N (that skews toward mega-brands like google.com
    that will trivially dominate every feature); instead we sample across
    a wider rank band so the legit class includes smaller/less-hardened
    but still legitimate sites, which is what the model needs to generalize.

    IMPORTANT (fixed after Phase 3.3 baseline review): we do NOT just emit
    "https://{domain}" for every legit URL. That produced a hard
    path_length == 0 for 100% of the legit class, which is not what real
    browsing traffic looks like and gave the model a trivial non-phishing
    "path exists or not" shortcut instead of an actual phishing signal
    (RF baseline hit an unrealistic 1.0000 across every metric on this
    leak). Instead, for each sampled domain we try to resolve the real
    landing URL by following redirects (many sites bounce domain.com ->
    domain.com/some/real/path), and fall back to a synthesized-but-plausible
    path when the live fetch fails or times out, so the legit class has
    realistic path/subdomain/query variance either way.

Usage (run this INSIDE the Docker container, not on the host — it needs
the same network path Phase 2's WHOIS retry logic was built against):

    docker compose exec api python scripts/build_training_dataset.py \\
        --phishing-count 2000 --legit-count 2000 --concurrency 20

Safe to interrupt (Ctrl+C) and re-run — it skips URLs already present in
the output CSV. NOTE: if you're re-running this after the legit-URL fix
above, delete the old training_dataset.csv first — the resume logic
matches on exact URL string, so old bare-domain rows won't be recognized
as duplicates of the new realistic-path rows and you'll end up with both,
silently reintroducing the leak into half the legit class.
"""
from __future__ import annotations

import argparse
import asyncio
import csv
import io
import random
import subprocess
import sys
import tempfile
import zipfile
from pathlib import Path
from urllib.request import urlopen

import aiohttp

# Make `features.*` importable when run as `python scripts/build_training_dataset.py`
# from the backend/ directory (same convention the test suite uses).
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from features.pipeline import FeaturePipeline  # noqa: E402

OPENPHISH_MIRROR = "https://github.com/openphish/public_feed.git"
TRANCO_URL = "https://tranco-list.eu/top-1m.csv.zip"

# The 41 keys FeaturePipeline.extract() returns, in a fixed order, so the
# CSV has stable columns regardless of dict ordering.
FEATURE_KEYS = None  # populated at runtime from a live extract() call


# ─────────────────────────────────────────────────────────────────────────
# Source 1: phishing URLs from the OpenPhish GitHub mirror
# ─────────────────────────────────────────────────────────────────────────
def fetch_phishing_urls(target_count: int, max_commits: int = 60) -> list[str]:
    """Walk the OpenPhish mirror's commit history, newest first, collecting
    unique URLs from each historical feed.txt snapshot until target_count
    is reached (or history runs out)."""
    tmpdir = tempfile.mkdtemp(prefix="openphish_mirror_")
    print(f"[phishing] cloning OpenPhish mirror into {tmpdir} ...")
    subprocess.run(
        ["git", "clone", "--quiet", f"--depth={max_commits}", OPENPHISH_MIRROR, tmpdir],
        check=True,
    )

    commits = subprocess.run(
        ["git", "-C", tmpdir, "log", "--format=%H"],
        capture_output=True, text=True, check=True,
    ).stdout.split()

    seen: set[str] = set()
    for i, sha in enumerate(commits):
        result = subprocess.run(
            ["git", "-C", tmpdir, "show", f"{sha}:feed.txt"],
            capture_output=True, text=True,
        )
        if result.returncode != 0:
            continue  # some early commits may not have feed.txt at that path
        for line in result.stdout.splitlines():
            line = line.strip()
            if line:
                seen.add(line)
        if len(seen) >= target_count:
            print(f"[phishing] reached {len(seen)} unique URLs after {i + 1} commits")
            break
    else:
        print(f"[phishing] exhausted {len(commits)} commits, got {len(seen)} unique URLs "
              f"(wanted {target_count}) — consider raising --max-commits")

    urls = list(seen)
    random.shuffle(urls)
    return urls[:target_count]


# ─────────────────────────────────────────────────────────────────────────
# Source 2: legitimate URLs from Tranco
# ─────────────────────────────────────────────────────────────────────────

# Fallback path templates for domains where the live fetch fails/times out —
# ensures the legit class still has realistic path/subdomain/query variance
# instead of a hard zero, even when we can't reach the real site.
_PATH_TEMPLATES = [
    "",  # some legit visits ARE the bare domain — keep a slice of these, just not 100%
    "/login",
    "/about",
    "/products",
    "/blog/{slug}",
    "/en-us/home",
    "/account/settings",
    "/search?q={slug}",
    "/support/contact",
    "/{slug}/index.html",
    "/api/v1/status",
]
_SLUG_WORDS = ["update", "pricing", "team", "docs", "signup", "help", "news", "profile"]


def _synthesize_path(domain: str) -> str:
    template = random.choice(_PATH_TEMPLATES)
    if "{slug}" in template:
        template = template.replace("{slug}", random.choice(_SLUG_WORDS))
    return f"https://{domain}{template}"


async def _resolve_real_url(session: aiohttp.ClientSession, domain: str,
                             sem: asyncio.Semaphore) -> str:
    """Try to find where this domain actually lands (following redirects).
    Falls back to a synthesized path on any failure so we never emit a
    bare-domain-only URL just because the network hiccuped."""
    async with sem:
        try:
            async with session.get(
                f"https://{domain}",
                timeout=aiohttp.ClientTimeout(total=6),
                allow_redirects=True,
                max_redirects=5,
            ) as resp:
                final_url = str(resp.url)
                # If it really did resolve to the bare domain with no path,
                # that's a genuine legit URL shape — keep it as-is.
                return final_url
        except Exception:
            return _synthesize_path(domain)


async def _fetch_legit_urls_async(domains: list[str], concurrency: int) -> list[str]:
    sem = asyncio.Semaphore(concurrency)
    connector = aiohttp.TCPConnector(limit=concurrency, ssl=False)
    async with aiohttp.ClientSession(connector=connector) as session:
        tasks = [_resolve_real_url(session, d, sem) for d in domains]
        results = []
        for i, coro in enumerate(asyncio.as_completed(tasks)):
            results.append(await coro)
            if (i + 1) % 200 == 0:
                print(f"[legit] resolved {i + 1}/{len(domains)}")
        return results


def fetch_legit_urls(target_count: int, rank_band: int = 50_000,
                      concurrency: int = 30) -> list[str]:
    """Download the Tranco top-1M list, sample target_count domains from
    the top `rank_band` ranks, then resolve each to its real landing URL
    (with a synthesized-path fallback) so legit URLs have realistic shape
    instead of always being the bare domain."""
    print(f"[legit] downloading Tranco list from {TRANCO_URL} ...")
    with urlopen(TRANCO_URL, timeout=60) as resp:
        raw = resp.read()

    with zipfile.ZipFile(io.BytesIO(raw)) as zf:
        csv_name = next(n for n in zf.namelist() if n.endswith(".csv"))
        with zf.open(csv_name) as f:
            reader = csv.reader(io.TextIOWrapper(f, encoding="utf-8"))
            domains = [row[1] for row in reader if len(row) >= 2][:rank_band]

    sample = random.sample(domains, min(target_count, len(domains)))
    print(f"[legit] resolving real landing URLs for {len(sample)} domains "
          f"(this makes live HTTP requests, will take a few minutes) ...")
    return asyncio.run(_fetch_legit_urls_async(sample, concurrency))


# ─────────────────────────────────────────────────────────────────────────
# Run every labeled URL through the real FeaturePipeline
# ─────────────────────────────────────────────────────────────────────────
async def _extract_one(pipeline: FeaturePipeline, url: str, label: int,
                        sem: asyncio.Semaphore) -> dict | None:
    async with sem:
        try:
            features = await pipeline.extract(url)
        except Exception as exc:  # noqa: BLE001 — this is a best-effort bulk job
            print(f"[skip] {url}: {exc!r}")
            return None
    from urllib.parse import urlparse
    row = {"url": url, "domain": urlparse(url).netloc, "label": label}
    row.update(features)
    return row


async def build_dataset(labeled_urls: list[tuple[str, int]], concurrency: int,
                         output_path: Path) -> None:
    already_done: set[str] = set()
    write_header = not output_path.exists()
    if output_path.exists():
        with output_path.open(newline="") as f:
            already_done = {row["url"] for row in csv.DictReader(f)}
        print(f"[resume] {len(already_done)} URLs already in {output_path}, skipping those")

    todo = [(u, l) for u, l in labeled_urls if u not in already_done]
    if not todo:
        print("Nothing left to do.")
        return

    pipeline = FeaturePipeline()
    sem = asyncio.Semaphore(concurrency)
    lock = asyncio.Lock()
    fieldnames = None
    done_count = 0

    async def worker(url: str, label: int):
        nonlocal fieldnames, done_count, write_header
        row = await _extract_one(pipeline, url, label, sem)
        if row is None:
            return
        async with lock:
            if fieldnames is None:
                fieldnames = list(row.keys())
            with output_path.open("a", newline="") as f:
                writer = csv.DictWriter(f, fieldnames=fieldnames)
                if write_header:
                    writer.writeheader()
                    write_header = False
                writer.writerow(row)
            done_count += 1
            if done_count % 50 == 0:
                print(f"[progress] {done_count}/{len(todo)} done")

    await asyncio.gather(*(worker(u, l) for u, l in todo))
    print(f"[done] wrote {done_count} new rows to {output_path}")


# ─────────────────────────────────────────────────────────────────────────
def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                      formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--phishing-count", type=int, default=2000)
    parser.add_argument("--legit-count", type=int, default=2000)
    parser.add_argument("--concurrency", type=int, default=20,
                         help="Max concurrent DNS/WHOIS/SSL lookups in flight")
    parser.add_argument("--max-commits", type=int, default=60,
                         help="Max OpenPhish mirror commits to walk back through")
    parser.add_argument("--output", type=Path,
                         default=Path(__file__).resolve().parent.parent / "data" / "training_dataset.csv")
    parser.add_argument("--dry-run", action="store_true",
                         help="Only fetch/print URL counts, skip the network-heavy pipeline run")
    args = parser.parse_args()

    args.output.parent.mkdir(parents=True, exist_ok=True)

    phishing_urls = fetch_phishing_urls(args.phishing_count, args.max_commits)
    legit_urls = fetch_legit_urls(args.legit_count)
    print(f"Collected {len(phishing_urls)} phishing URLs, {len(legit_urls)} legit URLs")

    if args.dry_run:
        return

    labeled = [(u, 1) for u in phishing_urls] + [(u, 0) for u in legit_urls]
    random.shuffle(labeled)
    asyncio.run(build_dataset(labeled, args.concurrency, args.output))


if __name__ == "__main__":
    main()
